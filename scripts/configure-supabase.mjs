#!/usr/bin/env node
/**
 * Interactive Supabase env setup. Writes .env.local (never commit this file).
 * Usage: npm run configure:supabase
 */
import { createInterface } from 'node:readline/promises'
import { writeFileSync, existsSync, readFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { randomBytes } from 'node:crypto'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const envPath = resolve(root, '.env.local')

const rl = createInterface({ input: process.stdin, output: process.stdout })

function mask(v) {
  if (!v || v.length < 12) return v ? '[set]' : '[empty]'
  return `${v.slice(0, 8)}…${v.slice(-4)}`
}

console.log('\n── Supabase configuration ──\n')
console.log('Get your keys from: https://supabase.com/dashboard/project/_/settings/api')
console.log('(Replace _ with your project ref)\n')

let existing = {}
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, 'utf8').split('\n')) {
    const t = line.trim()
    if (!t || t.startsWith('#')) continue
    const eq = t.indexOf('=')
    if (eq === -1) continue
    existing[t.slice(0, eq).trim()] = t.slice(eq + 1).trim()
  }
  console.log('Existing .env.local found — press Enter to keep current values.\n')
}

async function ask(key, hint) {
  const cur = existing[key]
  const show = cur && !cur.includes('your') ? ` (${mask(cur)})` : ''
  const val = (await rl.question(`${key}${show}\n  ${hint}\n  > `)).trim()
  if (!val && cur && !cur.includes('your')) return cur
  return val
}

const url = await ask(
  'NEXT_PUBLIC_SUPABASE_URL',
  'Example: https://abcdefgh.supabase.co',
)
try {
  const parsed = new URL(url)
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') throw new Error('bad protocol')
} catch {
  console.error('\n❌ Invalid URL. Must start with https://')
  rl.close()
  process.exit(1)
}

const anonKey = await ask('NEXT_PUBLIC_SUPABASE_ANON_KEY', 'anon / public key (starts with eyJ…)')
const serviceKey = await ask('SUPABASE_SERVICE_ROLE_KEY', 'service_role key (secret — never commit)')

let cronSecret = existing.CRON_SECRET
if (!cronSecret || cronSecret.includes('your')) {
  cronSecret = randomBytes(32).toString('hex')
  console.log(`\nGenerated CRON_SECRET: ${cronSecret.slice(0, 8)}… (saved to .env.local)`)
}

const content = `# Generated by npm run configure:supabase — do not commit
NEXT_PUBLIC_SUPABASE_URL=${url}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceKey}
CRON_SECRET=${cronSecret}
`

writeFileSync(envPath, content, 'utf8')
rl.close()

console.log('\n✓ Wrote .env.local\n')
console.log('Next steps:')
console.log('  1. Supabase → SQL Editor → run supabase/setup-all.sql')
console.log('  2. npm run setup:rooms')
console.log('  3. Copy the same 4 vars to Vercel → Project → Environment Variables\n')
